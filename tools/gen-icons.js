// Writes apps/windows/src/native/webicons.rs from web/js/ui.js: the website's drawn icons and its Windows glyph map,
// so the app shows exactly the icon the website shows for the same name.
const fs = require('fs');
const root = 'C:/Users/JustinPC/Documents/GitHub/VolvixHome/';
const src = fs.readFileSync(root + 'web/js/ui.js', 'utf8');
const grab = (name) => { const a = src.indexOf('const ' + name + ' = {'); const b = src.indexOf('\n  };', a); return src.slice(a + ('const ' + name + ' = ').length, b + 4); };
const F = 'fill="currentColor" stroke="none"';
const ICONS = new Function('F', 'return (' + grab('ICONS').replace(/;\s*$/, '') + ')')(F);
const GLYPHS = new Function('return (' + grab('GLYPHS').replace(/;\s*$/, '') + ')')();
let out = '//! The website\'s icons (web/js/ui.js), so both show the same picture for the same name. Generated by tools/gen-icons.js:\n' +
  '//! don\'t edit by hand; change the icon on the website and run the tool again.\n\n' +
  '/// Drawn icons: the inside of a 24 by 24 SVG, stroked 2 wide with round ends (white; the app tints it).\n' +
  'pub const ICONS: &[(&str, &str)] = &[\n';
for (const k of Object.keys(ICONS)) out += '    ("' + k + '", r##"' + ICONS[k].replace(/currentColor/g, 'white') + '"##),\n';
out += '];\n\n/// On Windows the website uses the system icon font for these names (the same glyphs the app uses).\npub const GLYPHS: &[(&str, char)] = &[\n';
for (const k of Object.keys(GLYPHS)) out += '    ("' + k + '", \'\\u{' + GLYPHS[k] + '}\'),\n';
out += '];\n';
fs.writeFileSync(root + 'apps/windows/src/native/webicons.rs', out);
console.log(Object.keys(ICONS).length + ' icons, ' + Object.keys(GLYPHS).length + ' glyphs');
